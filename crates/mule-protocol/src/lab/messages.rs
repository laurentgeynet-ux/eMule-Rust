//! Strongly-typed messages for the deterministic laboratory protocol (`PR_LAB = 0xEE`).

use bytes::{Buf, BufMut, Bytes, BytesMut};

use crate::error::ProtocolError;
use crate::framing::RawPacket;
use crate::limits::MAX_STRING_BYTES;
use crate::types::{PeerId, PR_LAB};

/// Opcode for client Hello handshake greeting.
pub const LAB_OP_HELLO: u8 = 0x01;
/// Opcode for server HelloAck handshake response.
pub const LAB_OP_HELLO_ACK: u8 = 0x02;
/// Opcode announcing available file offer.
pub const LAB_OP_FILE_OFFER: u8 = 0x03;
/// Opcode requesting a block of file data.
pub const LAB_OP_REQUEST_BLOCK: u8 = 0x04;
/// Opcode carrying block data payload.
pub const LAB_OP_BLOCK_DATA: u8 = 0x05;
/// Opcode signaling block request rejection.
pub const LAB_OP_BLOCK_REJECTED: u8 = 0x06;
/// Opcode for graceful connection closure.
pub const LAB_OP_GOODBYE: u8 = 0x07;
/// Opcode reporting protocol diagnostic error.
pub const LAB_OP_PROTOCOL_ERROR: u8 = 0x08;

/// Reason codes for block transfer rejection.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
#[repr(u8)]
pub enum LabRejectReason {
    /// File is not hosted or shared by the source.
    FileNotFound = 0x01,
    /// Requested block range is out of bounds or invalid.
    InvalidRange = 0x02,
    /// Source is busy or upload capacity exhausted.
    Busy = 0x03,
    /// Session is not in a valid state for block transfers.
    NotReady = 0x04,
    /// Other unspecified failure.
    Unspecified = 0xFF,
}

impl LabRejectReason {
    /// Converts a raw byte to a reject reason.
    pub fn from_u8(val: u8) -> Self {
        match val {
            0x01 => Self::FileNotFound,
            0x02 => Self::InvalidRange,
            0x03 => Self::Busy,
            0x04 => Self::NotReady,
            _ => Self::Unspecified,
        }
    }
}

/// High-level messages exchanged during laboratory loopback testing.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum LabMessage {
    /// Handshake initiator greeting.
    Hello {
        /// Supported lab protocol version (e.g. 1).
        client_version: u32,
        /// Ephemeral 16-byte challenge nonce generated by initiator.
        nonce: [u8; 16],
        /// Ephemeral peer identifier.
        peer_id: PeerId,
    },

    /// Handshake receiver acknowledgment.
    HelloAck {
        /// Selected lab protocol version.
        server_version: u32,
        /// Nonce echoing the initiator's nonce to confirm connection pairing.
        nonce_ack: [u8; 16],
        /// Ephemeral peer identifier of receiver.
        peer_id: PeerId,
    },

    /// Announcement of an available file offered by a peer.
    FileOffer {
        /// 16-byte eD2K file hash.
        file_hash: [u8; 16],
        /// Total file size in bytes.
        file_size: u64,
        /// Display name of the file.
        name: String,
    },

    /// Request for a specific block of data.
    RequestBlock {
        /// 16-byte eD2K file hash.
        file_hash: [u8; 16],
        /// Absolute byte offset in file.
        start_offset: u64,
        /// Requested byte length (up to 184,320 bytes).
        length: u32,
    },

    /// Payload delivery of requested block data.
    BlockData {
        /// 16-byte eD2K file hash.
        file_hash: [u8; 16],
        /// Absolute byte offset in file.
        start_offset: u64,
        /// Raw block data bytes.
        data: Bytes,
    },

    /// Rejection of a requested block.
    BlockRejected {
        /// 16-byte eD2K file hash.
        file_hash: [u8; 16],
        /// Absolute byte offset requested.
        start_offset: u64,
        /// Rejection reason.
        reason: LabRejectReason,
    },

    /// Clean closure notification.
    Goodbye {
        /// Descriptive reason for termination.
        reason: String,
    },

    /// Protocol diagnostic error message.
    ProtocolError {
        /// Error status code.
        code: u16,
        /// Diagnostic text message.
        message: String,
    },
}

impl LabMessage {
    /// Serializes the high-level message into a framed [`RawPacket`].
    pub fn to_raw_packet(&self) -> Result<RawPacket, ProtocolError> {
        let mut buf = BytesMut::new();
        let opcode = match self {
            Self::Hello {
                client_version,
                nonce,
                peer_id,
            } => {
                buf.put_u32_le(*client_version);
                buf.put_slice(nonce);
                buf.put_slice(peer_id.as_bytes());
                LAB_OP_HELLO
            }
            Self::HelloAck {
                server_version,
                nonce_ack,
                peer_id,
            } => {
                buf.put_u32_le(*server_version);
                buf.put_slice(nonce_ack);
                buf.put_slice(peer_id.as_bytes());
                LAB_OP_HELLO_ACK
            }
            Self::FileOffer {
                file_hash,
                file_size,
                name,
            } => {
                let name_bytes = name.as_bytes();
                if name_bytes.len() > MAX_STRING_BYTES {
                    return Err(ProtocolError::OversizedString {
                        len: name_bytes.len(),
                        limit: MAX_STRING_BYTES,
                    });
                }
                buf.put_slice(file_hash);
                buf.put_u64_le(*file_size);
                buf.put_u16_le(name_bytes.len() as u16);
                buf.put_slice(name_bytes);
                LAB_OP_FILE_OFFER
            }
            Self::RequestBlock {
                file_hash,
                start_offset,
                length,
            } => {
                buf.put_slice(file_hash);
                buf.put_u64_le(*start_offset);
                buf.put_u32_le(*length);
                LAB_OP_REQUEST_BLOCK
            }
            Self::BlockData {
                file_hash,
                start_offset,
                data,
            } => {
                buf.put_slice(file_hash);
                buf.put_u64_le(*start_offset);
                buf.put_slice(data);
                LAB_OP_BLOCK_DATA
            }
            Self::BlockRejected {
                file_hash,
                start_offset,
                reason,
            } => {
                buf.put_slice(file_hash);
                buf.put_u64_le(*start_offset);
                buf.put_u8(*reason as u8);
                LAB_OP_BLOCK_REJECTED
            }
            Self::Goodbye { reason } => {
                let r_bytes = reason.as_bytes();
                if r_bytes.len() > MAX_STRING_BYTES {
                    return Err(ProtocolError::OversizedString {
                        len: r_bytes.len(),
                        limit: MAX_STRING_BYTES,
                    });
                }
                buf.put_u16_le(r_bytes.len() as u16);
                buf.put_slice(r_bytes);
                LAB_OP_GOODBYE
            }
            Self::ProtocolError { code, message } => {
                let m_bytes = message.as_bytes();
                if m_bytes.len() > MAX_STRING_BYTES {
                    return Err(ProtocolError::OversizedString {
                        len: m_bytes.len(),
                        limit: MAX_STRING_BYTES,
                    });
                }
                buf.put_u16_le(*code);
                buf.put_u16_le(m_bytes.len() as u16);
                buf.put_slice(m_bytes);
                LAB_OP_PROTOCOL_ERROR
            }
        };

        Ok(RawPacket::new(PR_LAB, opcode, buf.freeze()))
    }

    /// Deserializes a [`RawPacket`] into a [`LabMessage`].
    pub fn from_raw_packet(packet: &RawPacket) -> Result<Self, ProtocolError> {
        if packet.protocol == crate::types::PR_EMULE_COMPRESSED {
            return Err(ProtocolError::CompressedProtocolUnsupported);
        }
        if packet.protocol != PR_LAB {
            return Err(ProtocolError::Framing(
                crate::error::FramingError::UnsupportedProtocol {
                    protocol: packet.protocol,
                },
            ));
        }

        let mut payload = packet.payload.clone();

        match packet.opcode {
            LAB_OP_HELLO => {
                if payload.len() < 4 + 16 + 16 {
                    return Err(ProtocolError::MalformedPayload(
                        "Hello payload too short".into(),
                    ));
                }
                let client_version = payload.get_u32_le();
                let mut nonce = [0u8; 16];
                payload.copy_to_slice(&mut nonce);
                let mut peer_bytes = [0u8; 16];
                payload.copy_to_slice(&mut peer_bytes);
                Ok(Self::Hello {
                    client_version,
                    nonce,
                    peer_id: PeerId::new(peer_bytes),
                })
            }
            LAB_OP_HELLO_ACK => {
                if payload.len() < 4 + 16 + 16 {
                    return Err(ProtocolError::MalformedPayload(
                        "HelloAck payload too short".into(),
                    ));
                }
                let server_version = payload.get_u32_le();
                let mut nonce_ack = [0u8; 16];
                payload.copy_to_slice(&mut nonce_ack);
                let mut peer_bytes = [0u8; 16];
                payload.copy_to_slice(&mut peer_bytes);
                Ok(Self::HelloAck {
                    server_version,
                    nonce_ack,
                    peer_id: PeerId::new(peer_bytes),
                })
            }
            LAB_OP_FILE_OFFER => {
                if payload.len() < 16 + 8 + 2 {
                    return Err(ProtocolError::MalformedPayload(
                        "FileOffer payload too short".into(),
                    ));
                }
                let mut file_hash = [0u8; 16];
                payload.copy_to_slice(&mut file_hash);
                let file_size = payload.get_u64_le();
                let name_len = payload.get_u16_le() as usize;
                if name_len > MAX_STRING_BYTES {
                    return Err(ProtocolError::OversizedString {
                        len: name_len,
                        limit: MAX_STRING_BYTES,
                    });
                }
                if payload.len() < name_len {
                    return Err(ProtocolError::MalformedPayload(
                        "FileOffer truncated string".into(),
                    ));
                }
                let name_bytes = payload.split_to(name_len);
                let name = String::from_utf8(name_bytes.to_vec())
                    .map_err(|e| ProtocolError::MalformedPayload(format!("Invalid UTF-8: {e}")))?;
                Ok(Self::FileOffer {
                    file_hash,
                    file_size,
                    name,
                })
            }
            LAB_OP_REQUEST_BLOCK => {
                if payload.len() < 16 + 8 + 4 {
                    return Err(ProtocolError::MalformedPayload(
                        "RequestBlock payload too short".into(),
                    ));
                }
                let mut file_hash = [0u8; 16];
                payload.copy_to_slice(&mut file_hash);
                let start_offset = payload.get_u64_le();
                let length = payload.get_u32_le();
                Ok(Self::RequestBlock {
                    file_hash,
                    start_offset,
                    length,
                })
            }
            LAB_OP_BLOCK_DATA => {
                if payload.len() < 16 + 8 {
                    return Err(ProtocolError::MalformedPayload(
                        "BlockData payload too short".into(),
                    ));
                }
                let mut file_hash = [0u8; 16];
                payload.copy_to_slice(&mut file_hash);
                let start_offset = payload.get_u64_le();
                let data = payload;
                Ok(Self::BlockData {
                    file_hash,
                    start_offset,
                    data,
                })
            }
            LAB_OP_BLOCK_REJECTED => {
                if payload.len() < 16 + 8 + 1 {
                    return Err(ProtocolError::MalformedPayload(
                        "BlockRejected payload too short".into(),
                    ));
                }
                let mut file_hash = [0u8; 16];
                payload.copy_to_slice(&mut file_hash);
                let start_offset = payload.get_u64_le();
                let reason = LabRejectReason::from_u8(payload.get_u8());
                Ok(Self::BlockRejected {
                    file_hash,
                    start_offset,
                    reason,
                })
            }
            LAB_OP_GOODBYE => {
                if payload.len() < 2 {
                    return Err(ProtocolError::MalformedPayload(
                        "Goodbye payload too short".into(),
                    ));
                }
                let r_len = payload.get_u16_le() as usize;
                if payload.len() < r_len {
                    return Err(ProtocolError::MalformedPayload(
                        "Goodbye truncated reason".into(),
                    ));
                }
                let r_bytes = payload.split_to(r_len);
                let reason = String::from_utf8(r_bytes.to_vec())
                    .map_err(|e| ProtocolError::MalformedPayload(format!("Invalid UTF-8: {e}")))?;
                Ok(Self::Goodbye { reason })
            }
            LAB_OP_PROTOCOL_ERROR => {
                if payload.len() < 4 {
                    return Err(ProtocolError::MalformedPayload(
                        "ProtocolError payload too short".into(),
                    ));
                }
                let code = payload.get_u16_le();
                let m_len = payload.get_u16_le() as usize;
                if payload.len() < m_len {
                    return Err(ProtocolError::MalformedPayload(
                        "ProtocolError truncated message".into(),
                    ));
                }
                let m_bytes = payload.split_to(m_len);
                let message = String::from_utf8(m_bytes.to_vec())
                    .map_err(|e| ProtocolError::MalformedPayload(format!("Invalid UTF-8: {e}")))?;
                Ok(Self::ProtocolError { code, message })
            }
            unknown => Err(ProtocolError::UnexpectedOpcode {
                expected: 0,
                got: unknown,
            }),
        }
    }
}
